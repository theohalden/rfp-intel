"""Run ten real cited Q&A examples; requires configured paid LLM access."""
from pathlib import Path
import json
import argparse
import sys
sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from agents.qa import QAEngine
from config import load_settings

QUESTIONS = [
    ('What is the submission deadline for Bid1 after all addendums?', 'Bid1'),
    ('What changed in Addendum 2 compared to the original RFP?', 'Bid1'),
    ('Which affidavits are required for the Dell laptop bid?', 'Bid2'),
    ('Compare the warranty requirements of Bid1 and Bid2.', None),
    ('Is a bid bond required, and if so, how much?', 'Bid1'),
    ('What processor is specified for part 379-BFNZ?', 'Bid2'),
    ('What RAM and storage are specified for the laptop?', 'Bid2'),
    ('What is the contract term and what renewal options are available?', 'Bid1'),
    ('What delivery window is required?', 'Bid2'),
    ('How may the proposal be submitted?', 'Bid1'),
]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--only', type=int, action='append', help='Refresh a numbered example in an existing complete log')
    args = parser.parse_args()
    settings = load_settings()
    engine = QAEngine(settings)
    results = json.loads((settings.paths.outputs / 'qa_log.json').read_text()) if args.only else []
    if args.only and (len(results) != len(QUESTIONS) or any(not 1 <= n <= len(QUESTIONS) for n in args.only)):
        raise ValueError('Refresh requires a complete log and valid example numbers')
    for i, (question, bid) in enumerate(QUESTIONS, 1):
        if args.only and i not in args.only:
            continue
        print(f'{i}/{len(QUESTIONS)}: {question}', flush=True)
        result = engine.ask(question, bid_id=bid)
        if args.only:
            results[i - 1] = result.model_dump(mode='json')
        else:
            results.append(result.model_dump(mode='json'))
        (settings.paths.outputs / 'qa_log.json').write_text(json.dumps(results, indent=2, ensure_ascii=False))
        lines = ['# Live cited Q&A examples', '', 'Generated by the real ReAct/search/guard workflow. Missing evidence is reported explicitly; these examples are not an answer-accuracy benchmark.', '']
        for n, item in enumerate(results, 1):
            lines.extend([f'## {n}. {item["question"]}', '', item['answer'], ''])
            if item['notes']:
                lines.extend(['Evidence limits: ' + item['notes'], ''])
            for source in item['sources']:
                lines.extend([f'**{source["bid_id"]} — {source["file"]}, page {source["page"]}**', '', '> ' + source['quote'].replace('\n', '\n> '), ''])
            lines.extend([f'Trace: `{Path(item["trace_file"]).name}`', ''])
        (settings.paths.outputs / 'qa_log.md').write_text('\n'.join(lines))
    print('Saved outputs/qa_log.md and outputs/qa_log.json', flush=True)


if __name__ == '__main__':
    main()
